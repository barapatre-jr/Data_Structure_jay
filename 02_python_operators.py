a = 10
b = 5

# Arithmetic
print("Addition:", a + b)
print("Division:", a / b)

# Relational
print("a > b:", a > b)

# Logical
print("a > 5 and b < 10:", a > 5 and b < 10)

# Bitwise
print("a & b:", a & b)

# Assignment
a += b
print("Updated a:", a)

# Membership
list1 = [1, 2, 3, 4]
print("2 in list1:", 2 in list1)

# Identity
x = 10
y = 10
print("x is y:", x is y)
